void test_patch_jump(void) {
    TEST("patch_jump");
    
    CodeGenerator* codegen = codegen_create();
    Chunk chunk;
    chunk_init(&chunk);
    
    codegen->current_function = function_context_create(NULL, "test");
    codegen->current_function->chunk = &chunk;
    
    int jump_offset = codegen_emit_jump(codegen, OPCODE_JUMP);
    
    // Emit some instructions
    codegen_emit_byte(codegen, OPCODE_NOP);
    codegen_emit_byte(codegen, OPCODE_NOP);
    codegen_emit_byte(codegen, OPCODE_NOP);
    
    // Patch the jump
    codegen_patch_jump(codegen, jump_offset);
    
    // Verify jump was patched (should jump 3 bytes forward)
    uint16_t jump = (chunk.code[jump_offset] << 8) | chunk.code[jump_offset + 1];
    ASSERT_EQ(jump, 3, "Jump should be 3 bytes");
    
    chunk_free(&chunk);
    codegen_destroy(codegen);
    TEST_END;
}

