static int tests_run = 0;
static int tests_passed = 0;
static int tests_failed = 0;

#define TEST(name) \
    do { \
        tests_run++; \
        printf("Test %d: %s...", tests_run, name); \
        fflush(stdout);

#define TEST_END \
        tests_passed++; \
        printf(" PASSED\n"); \
    } while(0)

#define TEST_FAIL(msg) \
    do { \
        tests_failed++; \
        printf(" FAILED: %s\n", msg); \
        return; \
    } while(0)

#define ASSERT_TRUE(cond, msg) \
    if (!(cond)) TEST_FAIL(msg)

#define ASSERT_FALSE(cond, msg) \
    if (cond) TEST_FAIL(msg)

#define ASSERT_EQ(a, b, msg) \
    if ((a) != (b)) TEST_FAIL(msg)

#define ASSERT_DOUBLE_EQ(a, b, msg) \
    if (fabs((a) - (b)) > 0.0001) TEST_FAIL(msg)

// Helper: Create a simple literal node
static AstNode* create_literal_node(double value) {
    AstNode* node = malloc(sizeof(AstNode));
    node->kind = AST_NODE_LITERAL;
    node->as.literal.type = NULL;
    node->as.literal.value.f64 = value;
    return node;
}

// Helper: Create a binary op node
static AstNode* create_binary_op_node(const char* op, AstNode* left, AstNode* right) {
    AstNode* node = malloc(sizeof(AstNode));
    node->kind = AST_NODE_BINARY_OP;
    node->as.binary_op.op = op;
    node->as.binary_op.left = left;
    node->as.binary_op.right = right;
    return node;
}

// Helper: Free AST node
static void free_ast_node(AstNode* node) {
    if (!node) return;
    
    if (node->kind == AST_NODE_BINARY_OP) {
        free_ast_node(node->as.binary_op.left);
        free_ast_node(node->as.binary_op.right);
    }
    
    free(node);
}

